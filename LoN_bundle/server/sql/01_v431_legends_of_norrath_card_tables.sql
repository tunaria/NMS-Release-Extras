-- The card tables and the loot-card -> EQ item map. world.exe runs the card service.
--   lon_account          one row per EQ account that has opened the card game
--   lon_card             every card copy a player owns (instance number = id)
--   lon_deck             decks the player saved (the client's own EQDeck bytes)
--   lon_session          one-time login tokens zone hands the client's DLL
--   lon_game             single-player games the client reported (begin/end) -- the
--                        reward checks need a begin before the end
--   lon_reward_claim     rewards already paid: one per scenario x difficulty x variant,
--                        and the first-win loot card (difficulty = -1)
--   lon_delivery         products granted elsewhere (your shop, a GM, an NPC) waiting to be
--                        sent: INSERT (account_id, archetype, quantity, source); world delivers
--                        it into the card collection when that account is in the card game
--   lon_loot_redemption  loot cards turned into EQ items (log)
--   lon_loot_item        which EQ item each EverQuest loot card gives (EQ item ids as in PEQ)

CREATE TABLE IF NOT EXISTS `lon_account` (
  `account_id` int unsigned NOT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `starter_granted` tinyint unsigned NOT NULL DEFAULT 0,
  `last_monthly` int unsigned NOT NULL DEFAULT 0,
  PRIMARY KEY (`account_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `lon_card` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `account_id` int unsigned NOT NULL,
  `archetype` int unsigned NOT NULL,
  `series` int unsigned NOT NULL DEFAULT 0,
  `tradable` tinyint unsigned NOT NULL DEFAULT 1,
  `source` varchar(32) NOT NULL DEFAULT '',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `account_archetype` (`account_id`,`archetype`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `lon_deck` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `account_id` int unsigned NOT NULL,
  `name` varchar(128) NOT NULL,
  `archetype` int unsigned NOT NULL DEFAULT 0,
  `deck` mediumblob NOT NULL,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `account_name` (`account_id`,`name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `lon_session` (
  `token` char(32) NOT NULL,
  `account_id` int unsigned NOT NULL,
  `character_id` int unsigned NOT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `expires_at` datetime NOT NULL,
  PRIMARY KEY (`token`),
  KEY `account_id` (`account_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `lon_game` (
  `account_id` int unsigned NOT NULL,
  `game_id` int NOT NULL,
  `game_type` int NOT NULL DEFAULT 0,
  `script` varchar(64) NOT NULL DEFAULT '',
  `began_at` datetime NULL DEFAULT NULL,
  `ended_at` datetime NULL DEFAULT NULL,
  `result` int NOT NULL DEFAULT 0,
  `turns` int NOT NULL DEFAULT 0,
  PRIMARY KEY (`account_id`,`game_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `lon_reward_claim` (
  `account_id` int unsigned NOT NULL,
  `script` varchar(64) NOT NULL,
  `difficulty` int NOT NULL,
  `variant` int NOT NULL DEFAULT 0,
  `archetype` int unsigned NOT NULL DEFAULT 0,
  `claimed_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`account_id`,`script`,`difficulty`,`variant`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `lon_delivery` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `account_id` int unsigned NOT NULL,
  `archetype` int unsigned NOT NULL,
  `quantity` int unsigned NOT NULL DEFAULT 1,
  `source` varchar(32) NOT NULL DEFAULT '',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `delivered_at` datetime NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `account_pending` (`account_id`,`delivered_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `lon_loot_redemption` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `account_id` int unsigned NOT NULL,
  `character_id` int unsigned NOT NULL,
  `card_archetype` int unsigned NOT NULL,
  `item_id` int unsigned NOT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `account_id` (`account_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `lon_loot_item` (
  `card_archetype` int unsigned NOT NULL,
  `item_id` int unsigned NOT NULL,
  PRIMARY KEY (`card_archetype`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

